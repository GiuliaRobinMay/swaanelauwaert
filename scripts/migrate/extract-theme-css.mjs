// Builds src/styles/wp-theme.css from the mirrored homepage: every local
// stylesheet it links plus every inline <style id="..."> block (except the
// per-page block-supports CSS, which the content migration stores per page),
// in document order, with font URLs rewritten to /fonts/. Also copies the
// theme fonts and the custom Floreal font into public/fonts/.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..", "..");
const RAW = path.join(ROOT, "mirror/raw/swaanelauwaert.com");
// Walk every mirrored page: WordPress only enqueues the CSS of the blocks a page
// uses, so the union of all pages is needed to style every block type.
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.name.endsWith(".html") ? [path.join(d, e.name)] : []));
const files = [path.join(RAW, "en.html"), path.join(RAW, "nl.html"), path.join(RAW, "fr.html"), ...walk(RAW).filter((f) => !/\/(en|nl|fr)\.html$/.test(f)).sort()];
const FONTS_OUT = path.join(ROOT, "public/fonts");
fs.mkdirSync(FONTS_OUT, { recursive: true });

const PER_PAGE = new Set(["core-block-supports-inline-css", "block-style-variation-styles-inline-css", "wp-emoji-styles-inline-css", "jetpack-stats-inline-css"]);
const parts = [];
const seen = new Set();
const re = /<link[^>]+rel=['"]stylesheet['"][^>]*href=['"]([^'"]+)['"][^>]*>|<style (?:id|class)=['"]([^'"]+)['"][^>]*>([\s\S]*?)<\/style>/g;
let pagesScanned = 0;
for (const file of files) {
  const html = fs.readFileSync(file, "utf8");
  const dir = path.dirname(file);
  const head = html.slice(0, html.indexOf("</head>"));
  pagesScanned++;
  let m;
  while ((m = re.exec(head))) {
    if (m[1]) {
      const href = m[1].replace(/&amp;/g, "&");
      const key = href.replace(/^(\.\.\/)+/, "");
      if (seen.has(key)) continue;
      seen.add(key);
      if (/^https?:/.test(href)) { parts.push(`/* external stylesheet skipped: ${href} */`); continue; }
      const cands = [path.resolve(dir, href), path.resolve(dir, decodeURIComponent(href)), path.join(RAW, key), path.join(RAW, decodeURIComponent(key))];
      const p = cands.find((f) => fs.existsSync(f));
      if (!p) { parts.push(`/* missing local stylesheet: ${href} */`); continue; }
      parts.push(`/* ==== ${key} ==== */\n` + fs.readFileSync(p, "utf8"));
    } else if (m[2]) {
      if (PER_PAGE.has(m[2])) continue;
      const key = "#" + m[2] + ":" + m[3].length + ":" + m[3].slice(0, 200);
      if (seen.has(key)) continue;
      seen.add(key);
      parts.push(`/* ==== inline ${m[2]} ==== */\n` + m[3]);
    }
  }
}
console.log(`scanned ${pagesScanned} pages`);
const copied = new Set();
const rewriteFonts = (text) => text.replace(/url\(\s*['"]?([^'")]+\.(woff2?|ttf|otf))['"]?\s*\)|src:\s*'([^']+\.(woff2?|ttf|otf))'/g, (all, u1, _e1, u2) => {
  const u = u1 || u2;
  const rel = u.replace(/^(\.\.\/)+/, "").replace(/^\/+/, "");
  const local = path.join(RAW, rel);
  const base = path.basename(u);
  if (fs.existsSync(local)) { fs.copyFileSync(local, path.join(FONTS_OUT, base)); copied.add(base); }
  else if (!fs.existsSync(path.join(FONTS_OUT, base))) console.warn("font not found locally:", u);
  return `url("/fonts/${base}")`;
});
for (let i = 0; i < parts.length; i++) parts[i] = rewriteFonts(parts[i]);
// Deduplicate at rule level (first occurrence wins) so repeated inline blocks only add new rules.
function splitRules(css) {
  const out = []; let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    const ch = css[i];
    if (ch === "{") depth++;
    else if (ch === "}") { depth--; if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; } }
  }
  const rest = css.slice(start).trim();
  if (rest) out.push(rest);
  return out.filter(Boolean);
}
const seenRules = new Set();
const dedupedParts = parts.map((part) => {
  const nl = part.indexOf("\n");
  const header = part.startsWith("/* ====") ? part.slice(0, nl) : "";
  const body = header ? part.slice(nl + 1) : part;
  const rules = splitRules(body).filter((r) => { const k = r.replace(/\s+/g, " "); if (r.startsWith("/*")) return true; if (seenRules.has(k)) return false; seenRules.add(k); return true; });
  return rules.length ? header + "\n" + rules.join("\n") : "";
}).filter(Boolean);
let css = dedupedParts.join("\n\n");
// Twenty Twenty-Five stylesheet references its own assets with relative urls; neutralise anything left.
css = css.replace(/url\((['"]?)wp-content\//g, "url($1/wp-content/");
fs.mkdirSync(path.join(ROOT, "src/styles"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "src/styles/wp-theme.css"), `/* Generated by scripts/migrate/extract-theme-css.mjs from the mirrored site. Do not edit by hand. */\n${css}\n`);
console.log(`wp-theme.css: ${(css.length / 1024).toFixed(0)} KB, ${parts.length} parts, fonts copied: ${copied.size}`);
